"""TableOracle = lookup layer over TRUTH TABLES generated from the deterministic DC/AC oracle (never an independent severity
calculation). Tables are indexed by LEXICOGRAPHIC rank. generate_truth_table() is the only producer and it calls
oracle.evaluate(); a loaded table carries the producing oracle's namespace (grid hash + order fingerprint + config + code)."""
from __future__ import annotations
import hashlib, json, platform
from pathlib import Path
import numpy as np
import scipy
from .. import __version__
from ..gridtwin.contingency import ContingencySpace, ContingencyError
from .hashing import oracle_config_dict
from .interface import CallCounter, GridFeatures, OracleRecord

STATUS = ["STABLE", "EXHAUSTED", "TOTAL_LOSS"]
F_NONCONV, F_EXHAUSTED, F_PMIN = 1, 2, 4
ARRAYS_FULL = {"S": "float64", "S0": "float64", "S_total": "float64", "rounds": "int16", "status": "int8",
               "flags": "uint8", "ladder": "int16", "n_trips": "int32"}

class TableError(RuntimeError):
    pass

# ---- GridFeatures <-> npz ------------------------------------------------------------------------------------------
def save_features(f: GridFeatures, path: Path):
    d = {n: v for n, v in vars(f).items() if isinstance(v, np.ndarray)}
    d["branch_keys"] = np.array(f.branch_keys, dtype=np.int64)
    d["_scalars"] = np.array(json.dumps({"L": f.L, "B": f.B, "base_mva": f.base_mva, "grid_hash": f.grid_hash,
                                         "order_fingerprint": f.order_fingerprint}))
    np.savez(path, **d)

def load_features(path: Path) -> GridFeatures:
    z = np.load(path, allow_pickle=False); sc = json.loads(str(z["_scalars"]))
    kw = {n: z[n] for n in z.files if n not in ("_scalars", "branch_keys")}
    for a in kw.values(): a.setflags(write=False)
    kw.setdefault("branch_x_pu", None)               # tables written before Phase 4 have no reactances
    return GridFeatures(L=sc["L"], B=sc["B"], base_mva=sc["base_mva"], grid_hash=sc["grid_hash"],
                        order_fingerprint=sc["order_fingerprint"], branch_keys=tuple(tuple(int(v) for v in r) for r in z["branch_keys"]), **kw)

def _sha(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for blk in iter(lambda: fh.read(1 << 22), b""): h.update(blk)
    return h.hexdigest()

def table_dir_name(grid_name, fidelity, k, namespace) -> str:
    return f"{grid_name}_{fidelity}_k{k}_{namespace[:12]}"

# ---- generation ----------------------------------------------------------------------------------------------------
def generate_truth_table(oracle, out_root, *, grid_name: str = "grid", chunk: int = 20_000, full_records: bool = True,
                         resume: bool = True, max_sets: int = 2_000_000, force: bool = False,
                         stop_after_chunks: int | None = None, workers: int = 1) -> Path:
    """Evaluate every set of Omega_k in lexicographic order through `oracle` and store the results. Refuses huge spaces
    unless force=True (normal tests/CI never generate large tables). Resumable at chunk granularity; each chunk is
    flushed and recorded in meta.json. `stop_after_chunks` exists only to test resumption."""
    sp = oracle.space; N = sp.N
    if N > max_sets and not force:
        raise TableError(f"C({sp.L},{sp.k}) = {N} exceeds max_sets={max_sets}; pass force=True / --force to generate a large table")
    d = Path(out_root) / table_dir_name(grid_name, oracle.fidelity, sp.k, oracle.namespace); d.mkdir(parents=True, exist_ok=True)
    with _TableLock(d):
        return _generate_locked(oracle, d, sp, N, chunk, full_records, resume, stop_after_chunks, workers, grid_name)

class _TableLock:
    """(Phase 7) One writer per table directory: '.lock' holds the writer's pid (O_EXCL). A live holder -> TableError; a dead holder's lock is stale."""
    def __init__(self, d: Path): self.p = Path(d) / ".lock"
    def __enter__(self):
        import os
        for _ in range(2):
            try:
                fd = os.open(self.p, os.O_CREAT | os.O_EXCL | os.O_WRONLY); os.write(fd, str(os.getpid()).encode()); os.close(fd); return self
            except FileExistsError:
                try: pid = int(self.p.read_text() or 0)
                except (OSError, ValueError): pid = 0
                alive = pid > 0 and Path(f"/proc/{pid}").exists() if Path("/proc").exists() else pid > 0
                if alive and pid != os.getpid(): raise TableError(f"table {self.p.parent.name} is being generated by pid {pid}")
                self.p.unlink(missing_ok=True)
        raise TableError(f"could not lock {self.p.parent}")
    def __exit__(self, *a): self.p.unlink(missing_ok=True)

def _generate_locked(oracle, d, sp, N, chunk, full_records, resume, stop_after_chunks, workers, grid_name):
    mp = d / "meta.json"; names = list(ARRAYS_FULL) if full_records else ["S"]
    if mp.exists():
        meta = json.loads(mp.read_text())
        if meta["namespace"] != oracle.namespace or meta["N"] != N or meta["chunk"] != chunk or meta["full_records"] != full_records:
            raise TableError("existing table directory was produced under a different namespace/chunk/record layout; refusing to resume")
        if meta["complete"] or not resume:
            if not meta["complete"]: raise TableError("incomplete table exists and resume=False")
            return d
        mode = "r+"
    else:
        meta = {"namespace": oracle.namespace, "fidelity": oracle.fidelity, "L": sp.L, "k": sp.k, "N": N, "chunk": chunk,
                "full_records": full_records, "grid_name": grid_name, "completed_chunks": 0, "complete": False,
                "order": "lexicographic", "tie_band": oracle.cfg.numerics.tie_band, "code_version": None,
                "oracle_config": oracle_config_dict(oracle.cfg, oracle.fidelity, getattr(oracle, "fast_path", False)),
                "software": {"doomsday": __version__, "python": platform.python_version(), "numpy": np.__version__, "scipy": scipy.__version__},
                "sha256": {}}
        from .hashing import code_version
        meta["code_version"] = code_version()
        mode = "w+"
    arr = {n: np.lib.format.open_memmap(d / f"{n}.npy", mode=mode, dtype=ARRAYS_FULL[n], shape=(N,)) for n in names}
    save_features(oracle.structure(), d / "features.npz")
    done = meta["completed_chunks"]; nchunks = -(-N // chunk)
    ranges = [(c, c * chunk, min((c + 1) * chunk, N)) for c in range(done, nchunks)]
    if workers > 1 and len(ranges) > 1:              # (Phase 7) same oracle code in forked workers; chunks are written IN ORDER -> identical files
        import multiprocessing as _mpx
        global _WORKER
        _WORKER = (oracle, full_records); pool = _mpx.get_context("fork").Pool(workers); results = pool.imap(_chunk_records, [(lo, hi) for _, lo, hi in ranges])
    else:
        pool = None; results = (_records(oracle, full_records, lo, hi) for _, lo, hi in ranges)
    for (c, lo, hi), rec in zip(ranges, results):
        for n in names: arr[n][lo:hi] = rec[n]
        for a in arr.values(): a.flush()
        meta["completed_chunks"] = c + 1; mp.write_text(json.dumps(meta, indent=1))
        if stop_after_chunks is not None and c + 1 - done >= stop_after_chunks and c + 1 < nchunks:
            if pool is not None: pool.terminate()
            return d
    if pool is not None: pool.close(); pool.join()
    for a in arr.values(): a.flush()
    del arr
    meta["sha256"] = {n: _sha(d / f"{n}.npy") for n in names}; meta["complete"] = True
    mp.write_text(json.dumps(meta, indent=1))
    return d

_WORKER = None
def _records(oracle, full_records: bool, lo: int, hi: int) -> dict:
    """Evaluate ranks [lo, hi) through oracle.evaluate (the only producer path) and return the column arrays."""
    X = oracle.space.unrank_batch(np.arange(lo, hi, dtype=np.int64))
    if not full_records: return {"S": oracle.severity_batch(X)}
    out = {n: np.empty(hi - lo, dtype=ARRAYS_FULL[n]) for n in ARRAYS_FULL}
    for i, row in enumerate(X):
        r = oracle.evaluate(tuple(int(v) for v in row))
        out["S"][i] = r.S; out["S0"][i] = r.S0; out["S_total"][i] = np.nan if r.S_total is None else r.S_total
        out["rounds"][i] = r.rounds; out["status"][i] = STATUS.index(r.status)
        out["flags"][i] = (F_NONCONV if r.nonconv_flag else 0) | (F_EXHAUSTED if r.exhausted else 0) | (F_PMIN if r.pmin_violation else 0)
        out["ladder"][i] = -1 if r.ladder_step is None else r.ladder_step; out["n_trips"][i] = r.n_trips
    return out

def _chunk_records(bounds):
    oracle, full = _WORKER; return _records(oracle, full, *bounds)

# ---- tables and the oracle -----------------------------------------------------------------------------------------
class TruthTable:
    def __init__(self, d: Path, verify_integrity: bool = True):
        self.dir = Path(d); self.meta = json.loads((self.dir / "meta.json").read_text())
        if not self.meta["complete"]:
            raise TableError(f"table {self.dir} is incomplete ({self.meta['completed_chunks']} chunks done)")
        if verify_integrity:
            for n, h in self.meta["sha256"].items():
                if _sha(self.dir / f"{n}.npy") != h:
                    raise TableError(f"integrity check failed for {n}.npy in {self.dir}")
        self.arrays = {n: np.load(self.dir / f"{n}.npy", mmap_mode="r") for n in self.meta["sha256"]}
        if len(self.arrays["S"]) != self.meta["N"]:
            raise TableError("table length does not match N")
        self.features = load_features(self.dir / "features.npz")

class TableOracle:
    kind = "table"
    def __init__(self, tables: dict, k: int, expect_namespace: str | None = None, _family: CallCounter | None = None):
        if k not in tables: raise ValueError(f"no table for k={k}; have {sorted(tables)}")
        ns = {t.meta["namespace"] for t in tables.values()}
        if len(ns) != 1: raise TableError("tables come from different oracle namespaces")
        self.namespace = ns.pop()
        if expect_namespace is not None and self.namespace != expect_namespace:
            raise TableError("table namespace does not match the expected oracle namespace (different grid/config/code)")
        self._tables, self.k = tables, k
        t = tables[k]; self.fidelity = t.meta["fidelity"]; self._band = t.meta["tie_band"]
        f = t.features
        self.space = ContingencySpace(f.L, k, f.branch_keys); self.cost_counter = CallCounter()
        self.family_counter = _family if _family is not None else CallCounter()      # shared by with_k siblings: unique (k, set)
        if t.meta["L"] != f.L or t.meta["N"] != self.space.N: raise TableError("table/space size mismatch")

    @classmethod
    def load(cls, dirs, k: int, expect_namespace: str | None = None, verify_integrity: bool = True) -> "TableOracle":
        tabs = {}
        for d in ([dirs] if isinstance(dirs, (str, Path)) else dirs):
            t = TruthTable(d, verify_integrity); tabs[t.meta["k"]] = t
        return cls(tabs, k, expect_namespace)

    @property
    def meta(self): return self._tables[self.k].meta
    def _A(self, name):
        a = self._tables[self.k].arrays
        if name not in a: raise NotImplementedError(f"table stores only {sorted(a)} (generated with full_records=False)")
        return a[name]

    def _rec(self, r: int) -> OracleRecord:
        S, S0 = float(self._A("S")[r]), float(self._A("S0")[r]); st = float(self._A("S_total")[r]); fl = int(self._A("flags")[r]); lad = int(self._A("ladder")[r])
        return OracleRecord(S=S, S0=S0, C=S - S0, A=S / max(S0, 0.01), rounds=int(self._A("rounds")[r]), status=STATUS[int(self._A("status")[r])],
                            S_total=None if np.isnan(st) else st, nonconv_flag=bool(fl & F_NONCONV), ladder_step=None if lad < 0 else lad,
                            exhausted=bool(fl & F_EXHAUSTED), pmin_violation=bool(fl & F_PMIN), n_trips=int(self._A("n_trips")[r]))

    def evaluate(self, outage) -> OracleRecord:
        key = self.space.validate(outage); self.cost_counter.record(key, True); self.family_counter.record((self.k, key), True)
        return self._rec(self.space.rank(key))
    def severity(self, outage) -> float:
        key = self.space.validate(outage); self.cost_counter.record(key, True); self.family_counter.record((self.k, key), True)
        return float(self._A("S")[self.space.rank(key)])
    def severity_batch(self, outages) -> np.ndarray:
        a = np.asarray(outages)
        if a.ndim != 2 or a.shape[1] != self.k:
            raise ValueError(f"outages must have shape (n, {self.k}), got {a.shape}")
        X = np.sort(a, axis=1)
        out = np.asarray(self._A("S"))[self.space.rank_batch(X)].astype(np.float64)    # raises ContingencyError on invalid rows
        for row in X:
            t = tuple(int(v) for v in row); self.cost_counter.record(t, True); self.family_counter.record((self.k, t), True)
        return out
    def severity_ranks(self, ranks) -> np.ndarray:
        return self.severity_batch(self.space.unrank_batch(ranks))
    def all_severities(self) -> np.ndarray:
        """The whole table in lexicographic rank order (no cost accounting: reference data, not a search)."""
        return np.array(self._A("S"), dtype=np.float64)
    def is_high_severity(self, outage, tau: float) -> bool: return self.severity(outage) >= tau - self._band
    def exceeds(self, outage, y: float) -> bool: return self.severity(outage) > y + self._band
    def is_cascade_driven(self, outage, tau: float, delta: float) -> bool:
        r = self.evaluate(outage); return r.S >= tau - self._band and r.C >= delta - self._band
    def structure(self) -> GridFeatures: return self._tables[self.k].features
    def with_k(self, k: int) -> "TableOracle":
        if k not in self._tables: raise ValueError(f"TableOracle has no table for k={k} (have {sorted(self._tables)})")
        return TableOracle(self._tables, k, _family=self.family_counter)
    def cascade(self, outage):
        raise NotImplementedError("TableOracle stores severities, not cascade frames; use the DC/AC oracle for display")

    def verify_against(self, source, ranks=None) -> dict:
        """Compare with the oracle that (supposedly) produced the table; ranks=None checks every set. Exact equality."""
        if source.namespace != self.namespace: raise TableError("source oracle namespace differs from the table namespace")
        ranks = np.arange(self.space.N) if ranks is None else np.asarray(ranks)
        bad = 0
        full = "S0" in self._tables[self.k].arrays
        for r in ranks.tolist():
            x = self.space.unrank(r); s = source.evaluate(x)
            if (self._rec(r) if full else None) != (s if full else None) or float(self._A("S")[r]) != s.S: bad += 1
        return {"checked": int(len(ranks)), "mismatches": bad}
